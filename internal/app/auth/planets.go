package auth

// currentUserID — константа текущего пользователя. В этой лабораторной
// авторизации ещё нет, поэтому создатель и владелец всех сущностей
// фиксированы здесь. В ЛР4 константа заменяется на разбор токена.
const currentUserID = 1

// CurrentUserID — функция-singleton, возвращает всегда одно и то же
// значение. Используется во всех методах вместо хардкода: обработчики
// получают id из неё, а не из тела запроса, поэтому клиент не может
// подделать создателя записи.
func CurrentUserID() uint {
	return currentUserID
}
